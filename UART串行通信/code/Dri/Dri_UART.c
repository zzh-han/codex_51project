#include "Dri_UART.h"
#include <STC89C5xRC.H>

/**
 * @brief 初始化UART工作方式
 *
 * SCON是串口控制寄存器，写入0x50（二进制0101 0000）：
 *   SM0=0、SM1=1：选择方式1，即8位UART；每帧由起始位、8个数据位、停止位组成，
 *                 数据位低位先发。方式1的波特率需要另行配置。
 *   SM2=0：关闭多机通信筛选；本实验暂不使用第9位地址标志。
 *   REN=1：允许接收。它只打开接收器，不会自动读取数据，也不会自动启用中断。
 *   TB8、RB8、TI、RI=0：将第9位数据和收发状态标志初始化为0。
 *
 * 当前阶段尚未配置波特率发生器，也没有实现SBUF读写，因此这里只完成模式设置。
 */
void Dri_UART_Init(void)
{
    SCON = 0x50;
}
